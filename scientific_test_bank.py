def load_db():
    if os.path.exists(SCIENTIFIC_TESTS_FILE):
        try:
            with open(SCIENTIFIC_TESTS_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            pass
    return {"young_beekeepers": [], "master_beekeepers": []}


def save_db(db):
    try:
        with open(SCIENTIFIC_TESTS_FILE, "w", encoding="utf-8") as f:
            json.dump(db, f, ensure_ascii=False, indent=2)
    except Exception as e:
        logging.error(f"Fayl saqlashda xatolik ({SCIENTIFIC_TESTS_FILE}): {e}")


def auto_add_next_10_scientific_test(category: str) -> tuple[int, int, int]:
    """
    Berilgan yo'nalish (young_beekeepers yoki master_beekeepers) ga
    avtomatik ravishda 10 ta yangi ilmiy test savollari va javoblarini qo'shadi.
    
    Qaytaradi: (yangi_set_id, qoshilgan_soni, jami_soni)
    """
    db = load_db()
    current_list = db.get(category, [])
    
    # Joriy eng katta set_id ni aniqlash
    current_max_set = 1
    existing_q_texts = set()
    for q in current_list:
        s_id = q.get("set_id", 1)
        if s_id > current_max_set:
            current_max_set = s_id
        existing_q_texts.add(q.get("question", "").strip().lower())
    
    next_set_id = current_max_set + 1
    prefix = "yb" if category == "young_beekeepers" else "mb"
    start_q_id = len(current_list) + 1
    
    # Yangi 10 talik to'plamni tanlash
    bank = EXTRA_YOSH_SETS if category == "young_beekeepers" else EXTRA_USTOZ_SETS
    
    chosen_set = None
    # Avval bankdagi hali qo'shilmagan to'plamlarni qidiramiz
    for candidate_set in bank:
        # Tekshiramiz: bu to'plamdagi savollar allaqachon bormi?
        is_already_present = any(q["question"].strip().lower() in existing_q_texts for q in candidate_set)
        if not is_already_present:
            chosen_set = candidate_set
            break
            
    # Agar barcha tayyor to'plamlar tugagan bo'lsa, mavjud savollardan yangi sintez qilamiz
    if not chosen_set:
        source_pool = (EXTRA_YOSH_SETS[0] if category == "young_beekeepers" else EXTRA_USTOZ_SETS[0])
        chosen_set = []
        for i, q in enumerate(source_pool):
            copy_q = dict(q)
            copy_q["question"] = f"{copy_q['question']} (Серия #{next_set_id})"
            chosen_set.append(copy_q)
            
    # 10 ta savolni bazaga qo'shish
    added_count = 0
    for idx, raw_q in enumerate(chosen_set[:10]):
        item = {
            "id": f"{prefix}_{start_q_id + idx}",
            "set_id": next_set_id,
            "q_num": idx + 1,
            "question": raw_q["question"],
            "options": raw_q["options"],
            "correct_option_id": raw_q["correct_option_id"],
            "institute": raw_q.get("institute", "Ўзбекистон Асаларичилик Илмий Маркази"),
            "explanation": raw_q.get("explanation", "Илмий тадқиқот институти томонидан тасдиқланган тўғри жавоб.")
        }
        current_list.append(item)
        added_count += 1
        
    db[category] = current_list
    save_db(db)
    
    return next_set_id, added_count, len(current_list)
